(function(){
const P=PCB.data;
function analyze(q){const o={};for(const x in P)o[x]=P[x][q[x]];const{CPU:u,GPU:g,Motherboard:mb,RAM:r,Storage:s,Cooler:cl,PSU:ps}=o;
const a={o,u,g,mb,r,s,cl,ps};a.draw=u.w+g.w+75;a.head=Math.round((ps.w-a.draw)/ps.w*100);a.need=Math.ceil(a.draw*1.3/50)*50;
a.g1=Math.round(Math.min(g.a,u.g*1.3+10)*.75+u.g*.25);a.g2=Math.round(Math.min(g.b,u.g*1.5+10)*.85+u.g*.15);a.g4=Math.round(Math.min(g.c,u.g*2+10)*.95+u.g*.05);
a.prod=Math.round(u.m*.6+r.sc*.2+s.sc*.2);a.cool=Math.round((cl.t-u.w)/cl.t*100);a.upg=u.s=='AM5'?2:0;a.upgT=a.upg?'Long: AM5 has more CPU generations ahead':'Limited: socket is at end of life';
const gap=u.g-(g.a+g.b)/2;a.bal=gap<-20?'cpu':gap>30?'gpu':'ok';
const K=[],add=(t,m)=>K.push([t,m]);
u.s==mb.s?add('ok',`${u.n} fits the ${mb.s} socket.`):add('bad',`${u.n} is ${u.s} but the board is ${mb.s}. They don't fit.`);
r.r==mb.r?add('ok',`${r.r} memory matches the board.`):add('bad',`Board takes ${mb.r} but RAM is ${r.r}. Not interchangeable.`);
ps.w>=a.need?add('ok',`${ps.w}W PSU covers the ${a.draw}W peak with room.`):ps.w>=a.draw*1.15?add('warn',`${ps.w}W PSU works but is tight. Aim for ${a.need}W+.`):add('bad',`${ps.w}W PSU is too weak for ${a.draw}W peak. Use ${a.need}W+.`);
if(cl.stock&&!u.stock)add('bad',`${u.n} has no cooler in the box. Choose a separate one.`);else if(cl.t<u.w)add('warn',`Cooler is rated about ${cl.t}W; this CPU can reach ${u.w}W.`);else add('ok','Cooler can handle the CPU.');
if(u.k&&!mb.oc)add('warn','Unlocked (K) chips only overclock on Z-series boards. They still run at stock speed here.');
if(mb.b)add('warn',`Older board: confirm ${u.n} is on its CPU support list. A BIOS update may be needed.`);
if(u.mc)add('warn','Intel microcode warning applies to this chip. See the note below.');
if(r.d==4)add('warn','4-stick memory kits often run slower than 2-stick kits on some boards.');
a.K=K;const pr=[],co=[];
if(a.g2>=80)pr.push('Strong 1440p gaming');else if(a.g1>=85)pr.push('Very smooth 1080p gaming');
if(g.v>=16)pr.push('16GB graphics memory suits high-resolution textures');
if(a.upg)pr.push('Room to upgrade the CPU later without a new board');
if(a.head>=40)pr.push('Plenty of PSU headroom for upgrades and quiet running');
if(r.cap>=32)pr.push(`${r.cap}GB RAM handles heavy multitasking`);
if(s.cap>=2000)pr.push('Large drive fits a big game library');
if(a.prod>=75)pr.push('Fast for video editing and other heavy work');
if(a.draw<=250)pr.push('Low power draw: cooler, quieter and cheaper to run');
if(a.cool>=30)pr.push('Cooler has spare capacity');
if(a.g2<55)co.push('Struggles at 1440p; best kept to 1080p');
if(g.v<=8)co.push(`${g.v}GB graphics memory may limit settings in newer games`);
if(!a.upg)co.push('Dead-end socket: upgrading the CPU later means a new board');
if(a.head>=0&&a.head<20)co.push('Little PSU headroom; upgrades may need a bigger PSU');
if(r.cap<=16)co.push('16GB RAM is the minimum; heavy multitasking may stutter');
if(r.cap>64)co.push('Over 64GB of RAM is overkill for gaming and most work. It only pays off for big video, 3D, virtual machines or AI jobs');
if(s.cap<=500)co.push('Small drive fills up quickly');
if(s.sata)co.push('SATA drive loads slower than NVMe');
if(a.draw>450)co.push('High power draw means more heat and fan noise');
if(a.prod<55)co.push('Not ideal for video editing or rendering');
if(u.mc)co.push('13th/14th Gen microcode issue: stability and wear risk, uncertain whether this chip has the fix');
if(a.bal=='cpu')co.push('CPU may hold the graphics card back');
if(a.bal=='gpu')co.push('CPU is stronger than this GPU can use for gaming');
K.filter(x=>x[0]=='bad').forEach(x=>co.unshift('Compatibility problem: '+x[1]));
a.pr=pr;a.co=co;return a}
PCB.analyze=analyze;
})();
